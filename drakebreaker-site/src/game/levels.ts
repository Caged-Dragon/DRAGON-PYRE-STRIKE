export const LEVELS: LevelDef[] = RAW.map((l, i) => {
  const cols = Math.max(...l.rows.map((r) => r.length));
  return {
    id: i + 1,
    name: l.name,
    flavor: l.flavor,
    cols,
    rows: l.rows.map((r) => r.padEnd(cols, ".")),
  };
});

export const LEVEL_COUNT = LEVELS.length;

/** Brick count per level, used by the chapter select for a difficulty hint. */
export function levelBrickCount(def: LevelDef) {
  let n = 0;
  for (const row of def.rows) for (const ch of row) if (ch !== "." && ch !== "o") n++;
  return n;
}
