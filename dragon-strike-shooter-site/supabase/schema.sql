-- Run this in the Supabase SQL editor once. Authentication stays managed by Supabase Auth.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  high_score bigint not null default 0,
  highest_level integer not null default 1 check (highest_level between 1 and 6),
  selected_dragon text not null default 'ember',
  total_runs integer not null default 0,
  updated_at timestamptz not null default now()
);

create table if not exists public.game_runs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mode text not null check (mode in ('endless', 'levels')),
  score bigint not null default 0,
  wave integer not null default 0,
  level integer not null default 1,
  dragon_id text not null,
  result text not null check (result in ('fallen', 'victory')),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.game_runs enable row level security;

create policy "Players can read their profile" on public.profiles
  for select using (auth.uid() = id);
create policy "Players can insert their profile" on public.profiles
  for insert with check (auth.uid() = id);
create policy "Players can update their profile" on public.profiles
  for update using (auth.uid() = id) with check (auth.uid() = id);

create policy "Players can read their runs" on public.game_runs
  for select using (auth.uid() = user_id);
create policy "Players can insert their runs" on public.game_runs
  for insert with check (auth.uid() = user_id);

create index if not exists game_runs_user_created_idx on public.game_runs(user_id, created_at desc);